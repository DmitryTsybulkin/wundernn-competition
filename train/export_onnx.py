def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--checkpoint", required=True)
    p.add_argument("--out-dir", required=True)
    p.add_argument("--valid-path", default=str(ROOT / "datasets/valid.parquet"))
    p.add_argument("--verify-sequences", type=int, default=50)
    p.add_argument("--official-check-sequences", type=int, default=50)
    p.add_argument("--throughput-rows", type=int, default=200_000)
    p.add_argument("--opset", type=int, default=17)
    p.add_argument(
        "--output-multiplier", type=float, default=None,
        help="override the checkpoint's stored calibration multiplier (default: use "
             "ckpt['output_multiplier'] if present, else 1.0 uncalibrated)",
    )
    return p.parse_args()


def build_and_export(checkpoint_path: str, out_dir: Path, output_multiplier: float | None = None) -> ModelConfig:
    ckpt = torch.load(checkpoint_path, map_location="cpu", weights_only=False)
    cfg: ModelConfig = ckpt["model_cfg"]
    model = SequenceModel(cfg)
    model.load_state_dict(ckpt["state_dict"])
    model.eval()

    multiplier = output_multiplier if output_multiplier is not None else ckpt.get("output_multiplier", 1.0)
    if multiplier != 1.0:
        # Scaling the head's weight+bias by c is exactly equivalent to scaling the final
        # prediction by c (to_targets is linear and homogeneous in raw — see model.py), and
        # bakes calibration into the ONNX graph at zero runtime cost. Global WP is only
        # scale-invariant BEFORE the metric's [-2,2] clip, so an uncalibrated model can lose
        # real score to clipping alone (notes/LOG.md 2026-09-17).
        with torch.no_grad():
            model.head.weight.mul_(multiplier)
            model.head.bias.mul_(multiplier)
            if model.skip is not None:
                # Final prediction is to_targets(head_raw) + skip(features); both
                # contributions must be scaled or the multiplier only partially applies.
                model.skip.weight.mul_(multiplier)
                model.skip.bias.mul_(multiplier)
    print(f"output multiplier baked into export: {multiplier} (checkpoint stored: {ckpt.get('output_multiplier')})")

    wrapper = StatefulStep(model)
    features = torch.zeros(1, 1, cfg.n_features, dtype=torch.float32)
    hidden = model.init_hidden(1)

    onnx_path = out_dir / "model.onnx"
    torch.onnx.export(
        wrapper,
        (features, hidden),
        str(onnx_path),
        input_names=["features", "hidden"],
        output_names=["prediction", "next_hidden"],
        opset_version=17,
        dynamo=False,
    )
    print(f"exported ONNX to {onnx_path} (valid_wp at checkpoint: {ckpt.get('valid_wp')})")
    return cfg


def write_solution(out_dir: Path, cfg: ModelConfig):
    (out_dir / "solution.py").write_text(
        SOLUTION_TEMPLATE.format(gru_layers=cfg.gru_layers, gru_hidden=cfg.gru_hidden)
    )


def make_zip(out_dir: Path, zip_path: Path):
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.write(out_dir / "solution.py", "solution.py")
        zf.write(out_dir / "model.onnx", "model.onnx")
    size_mb = zip_path.stat().st_size / 1e6
    print(f"wrote {zip_path} ({size_mb:.2f} MB, limit 20 MB)")
    assert size_mb < 20, "submission zip exceeds the 20MB limit"


class _OrtStepModel:
    """Drives the exported ONNX model via the PredictionModel contract, for cross-checking
    against the PyTorch model and for feeding utils.ScorerStepByStep."""

    def __init__(self, onnx_path: Path, cfg: ModelConfig):
        options = ort.SessionOptions()
        options.intra_op_num_threads = 1
        options.inter_op_num_threads = 1
        self.session = ort.InferenceSession(
            str(onnx_path), sess_options=options, providers=["CPUExecutionProvider"]
        )
        self.cfg = cfg
        self.hidden = np.zeros((cfg.gru_layers, 1, cfg.gru_hidden), dtype=np.float32)
        self.seq_ix = None

    def reset(self):
        self.hidden = np.zeros((self.cfg.gru_layers, 1, self.cfg.gru_hidden), dtype=np.float32)

    def step(self, features_row: np.ndarray):
        pred, self.hidden = self.session.run(
            None, {"features": features_row.reshape(1, 1, -1), "hidden": self.hidden}
        )
        return pred[0, 0]

    def predict(self, data_point):
        if data_point.seq_ix != self.seq_ix:
            self.seq_ix = data_point.seq_ix
            self.reset()
        pred = self.step(np.asarray(data_point.state, dtype=np.float32))
        if not data_point.need_prediction:
            return None
        return pred.astype(np.float32)


@torch.no_grad()
def verify_pytorch_vs_onnx(model: SequenceModel, onnx_path: Path, cfg: ModelConfig, valid_path: str, n_sequences: int):
    """Row-by-row: PyTorch stateful stepping vs ONNX Runtime stateful stepping, on real
    validation sequences. Reports max abs prediction diff and both WP scores."""
    pf = pq.ParquetFile(valid_path)
    n = min(n_sequences, pf.num_row_groups)
    ort_model = _OrtStepModel(onnx_path, cfg)

    max_abs_diff = 0.0
    torch_acc, onnx_acc = GlobalAccumulator(), GlobalAccumulator()
    for rg in range(n):
        features, targets, need, is_scored = _read_valid_sequence(pf, rg)
        mask = need & is_scored
        hidden = model.init_hidden(1)
        ort_model.reset()
        torch_preds = np.empty((len(features), 2), dtype=np.float32)
        onnx_preds = np.empty((len(features), 2), dtype=np.float32)
        for t in range(len(features)):
            x = torch.from_numpy(features[t].reshape(1, 1, -1))
            p, hidden = model(x, hidden)
            torch_preds[t] = p[0, 0].numpy()
            onnx_preds[t] = ort_model.step(features[t])
        max_abs_diff = max(max_abs_diff, float(np.abs(torch_preds - onnx_preds).max()))
        torch_acc.add(targets, torch_preds, mask)
        onnx_acc.add(targets, onnx_preds, mask)

    torch_wp = torch_acc.result()["weighted_pearson"]
    onnx_wp = onnx_acc.result()["weighted_pearson"]
    print(f"[verify] max |pytorch - onnx| prediction diff over {n} sequences: {max_abs_diff:.3e}")
    print(f"[verify] pytorch WP={torch_wp:.6f}  onnx WP={onnx_wp:.6f}  diff={abs(torch_wp-onnx_wp):.3e}")
    return max_abs_diff, torch_wp, onnx_wp


def measure_throughput(onnx_path: Path, cfg: ModelConfig, valid_path: str, target_rows: int):
    options = ort.SessionOptions()
    options.intra_op_num_threads = 1
    options.inter_op_num_threads = 1
    session = ort.InferenceSession(str(onnx_path), sess_options=options, providers=["CPUExecutionProvider"])
    pf = pq.ParquetFile(valid_path)

    hidden = np.zeros((cfg.gru_layers, 1, cfg.gru_hidden), dtype=np.float32)
    rows_done = 0
    t_start = time.perf_counter()
    rg = 0
    while rows_done < target_rows and rg < pf.num_row_groups:
        features, *_ = _read_valid_sequence(pf, rg)
        hidden.fill(0.0)
        for t in range(len(features)):
            _, hidden = session.run(None, {"features": features[t].reshape(1, 1, -1), "hidden": hidden})
            rows_done += 1
            if rows_done >= target_rows:
                break
        rg += 1
    elapsed = time.perf_counter() - t_start
    us_per_row = elapsed / rows_done * 1e6
    projected_minutes = us_per_row * 37_274_573 / 1e6 / 60
    print(
        f"[throughput] {rows_done:,} rows in {elapsed:.2f}s -> {us_per_row:.2f} us/row "
        f"(budget 96 us/row). Projected full test set: {projected_minutes:.1f} min (budget 60 min)."
    )
    return us_per_row


def main():
    args = parse_args()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    cfg = build_and_export(args.checkpoint, out_dir, output_multiplier=args.output_multiplier)
    write_solution(out_dir, cfg)
    make_zip(out_dir, out_dir / "submission.zip")

    ckpt = torch.load(args.checkpoint, map_location="cpu", weights_only=False)
    model = SequenceModel(cfg)
    model.load_state_dict(ckpt["state_dict"])
    model.eval()

    verify_pytorch_vs_onnx(model, out_dir / "model.onnx", cfg, args.valid_path, args.verify_sequences)
    measure_throughput(out_dir / "model.onnx", cfg, args.valid_path, args.throughput_rows)

    if args.official_check_sequences:
        # Slice the validation parquet down to the requested number of row groups so the
        # official ScorerStepByStep (slow, one row at a time) stays fast for a spot check.
        import pyarrow.parquet as pqw

        pf = pq.ParquetFile(args.valid_path)
        n = min(args.official_check_sequences, pf.num_row_groups)
        tmp_path = out_dir / f"_official_check_{n}.parquet"
        writer = None
        for rg in range(n):
            table = pf.read_row_group(rg, use_threads=False)
            if writer is None:
                writer = pqw.ParquetWriter(tmp_path, table.schema)
            writer.write_table(table, row_group_size=20_000)
        writer.close()

        sys.path.insert(0, str(out_dir))
        import importlib
        solution = importlib.import_module("solution")
        result = ScorerStepByStep(str(tmp_path)).score(solution.PredictionModel())
        print(f"[official-check on {n} sequences via solution.py] {result}")
        tmp_path.unlink()


if __name__ == "__main__":
    main()
